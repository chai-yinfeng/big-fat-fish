import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import { createHash } from 'node:crypto';
import { Authority } from '../src/engine.js';
import { createOperatorServer } from '../src/operator.js';

test('operator UI uses its separate credential and real world/persona operations', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'world-operator-'));
  const authority = new Authority({ file: path.join(dir, 'world.sqlite'), initialPaused: true });
  const token = 'o'.repeat(43), socketPath = path.join(dir, 'operator.sock');
  let resumed = 0;
  const app = createOperatorServer({ authority, socketPath, tokenHash: createHash('sha256').update(token).digest('hex'), origins: ['http://127.0.0.1:3081'], onResume: () => { resumed++; } });
  await app.start();
  t.after(async () => { await app.close(); authority.close(); fs.rmSync(dir, { recursive: true }); });
  const call = (method, target, data, key = token) => new Promise((resolve, reject) => {
    const req = http.request({ socketPath, path: target, method, headers: { origin: 'http://127.0.0.1:3081', authorization: `Bearer ${key}`, 'content-type': 'application/json' } }, res => {
      let raw = ''; res.on('data', chunk => { raw += chunk; }); res.on('end', () => resolve({ status: res.statusCode, body: JSON.parse(raw), cors: res.headers['access-control-allow-origin'] }));
    }); req.on('error', reject); req.end(data ? JSON.stringify(data) : undefined);
  });
  assert.equal((await call('GET', '/world', undefined, 'capability'.repeat(5))).status, 401);
  const first = await call('GET', '/world');
  assert.equal(first.cors, 'http://127.0.0.1:3081');
  assert.equal(first.body.value.world.paused, true);
  assert.deepEqual(first.body.value.channels.map(channel => channel.id), ['qq']);
  assert.equal(first.body.value.channels[0].status, 'not_configured');
  assert.equal((await call('POST', '/world/pause', { paused: false })).body.value.paused, false);
  assert.equal(resumed, 1);
  assert.equal((await call('POST', '/world/pause', { paused: true, expectedRevision: 1 })).status, 409);
  assert.equal((await call('POST', '/world/pause', { paused: true })).body.value.paused, true);
  assert.equal((await call('POST', '/test-conversations', { conversationId: 'test-first' })).status, 404);
  const edited = await call('POST', '/persona', { patch: { name: '大肥鱼' } });
  assert.equal(edited.body.value.personaRevision, 2);
  const persona = await call('GET', '/world');
  assert.equal(persona.body.value.persona.default.name, '大肥鱼'); assert.ok(persona.body.value.persona.default.examples.length > 0);
  const examples = [{ user: '你好', assistant: '嗨～' }, { user: '再见', assistant: '回头见' }];
  const full = await call('POST', '/persona', { patch: { userCallName: '小明', relationshipStage: 'friend', examples } });
  assert.equal(full.status, 200); assert.equal(full.body.value.personaRevision, 3); assert.deepEqual(full.body.value.persona.examples, examples);
  assert.equal(full.body.value.persona.name, '大肥鱼');
  assert.equal((await call('POST', '/persona', { patch: { examples: [{ user: '缺回复' }] } })).status, 400);
  assert.equal((await call('POST', '/persona', { patch: { mood: 'x' } })).status, 400);
  const preview = await call('POST', '/persona/preview', { patch: { name: '预览鱼' } });
  assert.equal(preview.status, 200); assert.equal(preview.body.value.limit, 1600);
  assert.ok(preview.body.value.text.startsWith('[人格]\n你是预览鱼。用户称呼：你。')); assert.equal(preview.body.value.chars, preview.body.value.text.length);
  assert.match(preview.body.value.text, /对方：再见\n你：回头见/);
  assert.equal((await call('POST', '/persona/preview', { patch: { name: '' } })).status, 400);
  assert.equal((await call('GET', '/world')).body.value.persona.revision, 3, 'preview never writes');
  assert.equal((await call('GET', '/world')).body.value.bindings.length, 0);
});
