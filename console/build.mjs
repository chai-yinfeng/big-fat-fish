import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('./', import.meta.url);
const read = file => readFile(new URL(file, root), 'utf8');
const stripModule = source => source.replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const dictionaries = Object.fromEntries(await Promise.all(['en', 'zh'].map(async locale => [locale, JSON.parse(await read(`locale/${locale}.json`))])));
const transport = stripModule(await read('operator-client.js') + '\n' + await read('dsh-client.js') + '\n' + await read('runtime-client.js'));
// Keep the existing product bundle entry: no dependency installation is needed
// to rebuild only this compatibility artifact.
const output = `// Generated by console/build.mjs. Edit the source inputs, then rebuild.\nwindow.__ModuleLoader__.load({\n  id: '@local/companion',\n  factory(require) {\nconst React = require('react');\nconst DICTIONARIES = ${JSON.stringify(dictionaries)};\n${transport}\n${stripModule(await read('view.js'))}\n${await read('dsh-entry.js')}\n  },\n});\n`;
await writeFile(new URL('client.js', root), output);
if (process.argv.includes('--standalone')) {
  const { build } = await import('esbuild');
  await mkdir(new URL('dist/', root), { recursive: true });
  const runtimeLicense = await read('node_modules/react/LICENSE');
  await build({ banner: { js: `/*! React / React DOM / Scheduler\n${runtimeLicense}\n*/` }, absWorkingDir: fileURLToPath(root), entryPoints: ['standalone-entry.js'], outfile: 'dist/console.js', bundle: true, format: 'esm', platform: 'browser', target: ['es2022'], minify: true, sourcemap: false, legalComments: 'inline', define: { 'process.env.NODE_ENV': '"production"' } });
  await copyFile(new URL('index.html', root), new URL('dist/index.html', root));
  await copyFile(new URL('icon.svg', root), new URL('dist/icon.svg', root));
}
